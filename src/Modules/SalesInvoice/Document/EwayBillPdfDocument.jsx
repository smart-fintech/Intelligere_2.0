import { Document, Page, StyleSheet, Text, View } from '@react-pdf/renderer'

/**
 * THE E-WAY BILL AS A VECTOR PDF - one A4 page, laid out as the earlier
 * version's e-Way Bill: the heading with Doc No. and Date, then five numbered
 * sections (E-Way Bill Details, Address Details, Goods Details with its totals
 * row, Transportation Details, Vehicle Details). A cancelled e-way bill is
 * stamped with a large red CANCELLED across the page.
 *
 *   <EwayBillPdfDocument model={toEwayBillModel(...)} />  - rendered to bytes by
 *   createEwayBillPdf (ewayBillPdf.js)
 */

const BLUE = '#1f5f99'
const RULE = '#c8c8c8'
const B = '#000'

const s = StyleSheet.create({
  page: { paddingVertical: 28, paddingHorizontal: 22, fontSize: 8, fontFamily: 'Helvetica', color: '#222' },
  title: { fontSize: 13, color: BLUE, marginBottom: 6 },
  docLine: { flexDirection: 'row', fontSize: 8.5, marginBottom: 1.5 },
  docLabel: { width: 42 },
  bold: { fontFamily: 'Helvetica-Bold' },
  docRule: { borderBottomWidth: 0.6, borderColor: RULE, marginTop: 6 },
  heading: { fontSize: 11, color: BLUE, marginTop: 10, paddingBottom: 3, borderBottomWidth: 0.8, borderColor: RULE },
  gridRow: { flexDirection: 'row', borderBottomWidth: 0.6, borderColor: RULE, paddingVertical: 3 },
  gridCell: { flex: 1, paddingRight: 6 },
  boxRow: { flexDirection: 'row', borderWidth: 0.8, borderColor: B },
  boxHead: { flexDirection: 'row' },
  boxHalf: { flex: 1, padding: 4 },
  boxDivider: { borderRightWidth: 0.8, borderColor: B },
  line: { marginBottom: 1.5 },
  table: { borderWidth: 0.8, borderColor: B, marginTop: 4 },
  tr: { flexDirection: 'row', borderBottomWidth: 0.8, borderColor: B },
  trLast: { flexDirection: 'row' },
  th: { fontFamily: 'Helvetica-Bold', padding: 3, borderRightWidth: 0.8, borderColor: B },
  td: { padding: 3, borderRightWidth: 0.8, borderColor: B },
  last: { borderRightWidth: 0 },
  watermark: {
    position: 'absolute',
    top: 360,
    left: 0,
    right: 0,
    textAlign: 'center',
    fontSize: 96,
    fontFamily: 'Helvetica-Bold',
    color: '#dc2626',
    opacity: 0.28,
    transform: 'rotate(-35deg)',
  },
})

const GOODS_COLUMNS = [
  ['hsn', 'HSN Code', '7%'],
  ['description', 'Product Name & Desc.', '47%'],
  ['quantity', 'Quantity:', '15%'],
  ['taxable', 'Taxable Amount Rs.', '12%'],
  ['rates', 'Tax Rate: (C+S+I)', '19%'],
]

const TOTAL_COLUMNS = [
  ['taxable', 'Tot.Taxable Amt'],
  ['cgst', 'CGST Amt'],
  ['sgst', 'SGST Amt'],
  ['igst', 'IGST Amt'],
  ['other', 'Other Amt'],
  ['total', 'Total Inv.Amt'],
]

const VEHICLE_COLUMNS = [
  ['mode', 'Mode:', '12%'],
  ['vehicleNo', 'Vehicle No:', '30%'],
  ['from', 'From:', '14%'],
  ['enteredDate', 'Entered Date:', '14%'],
  ['enteredBy', 'Entered By:', '30%'],
]

/** A cell of the details grid - its label, then its value. */
const Pair = ({ label, value, children }) => (
  <View style={s.gridCell}>
    <Text>
      {label} {value}
    </Text>
    {children}
  </View>
)

function Table({ columns, rows }) {
  return (
    <View style={s.table}>
      <View style={rows.length ? s.tr : s.trLast}>
        {columns.map(([key, label, width], index) => (
          <Text key={key} style={[s.th, width ? { width } : { flex: 1 }, index === columns.length - 1 ? s.last : null]}>
            {label}
          </Text>
        ))}
      </View>
      {rows.map((row, rowIndex) => (
        <View key={row.key ?? rowIndex} style={rowIndex === rows.length - 1 ? s.trLast : s.tr} wrap={false}>
          {columns.map(([key, , width], index) => (
            <Text key={key} style={[s.td, width ? { width } : { flex: 1 }, index === columns.length - 1 ? s.last : null]}>
              {row[key]}
            </Text>
          ))}
        </View>
      ))}
    </View>
  )
}

export default function EwayBillPdfDocument({ model }) {
  const { doc, details, from, to, goods, totals, transport, vehicle } = model
  return (
    <Document title={`e-Way Bill ${doc.no}`.trim()}>
      <Page size="A4" style={s.page}>
        <Text style={s.title}>{model.title}</Text>
        <View style={s.docLine}>
          <Text style={s.docLabel}>Doc No. :</Text>
          <Text style={s.bold}>{doc.no}</Text>
        </View>
        <View style={s.docLine}>
          <Text style={s.docLabel}>Date</Text>
          <Text>: </Text>
          <Text style={s.bold}>{doc.date}</Text>
        </View>
        <View style={s.docRule} />

        <Text style={s.heading}>1.E-Way Bill Details</Text>
        <View style={s.gridRow}>
          <Pair label="eWayBill No:" value={details.ewaybillNo} />
          <Pair label="Generated Date:" value={details.generatedDate} />
          <Pair label="Generated By:" value={details.generatedBy}>
            <Text>valid Upto: {details.validUpto}</Text>
          </Pair>
        </View>
        <View style={s.gridRow}>
          <Pair label="Mode:" value={details.mode} />
          <Pair label="Approx Distance:" value={details.distance} />
          <View style={s.gridCell} />
        </View>
        <View style={s.gridRow}>
          <Pair label="Type:" value={details.type} />
          <Pair label="Document Details:" value={details.documentDetails} />
          <Pair label="Transaction type:" value={details.transactionType} />
        </View>

        <Text style={s.heading}>2.Address Details</Text>
        <View style={[s.boxHead, { paddingVertical: 3 }]}>
          <Text style={{ flex: 1 }}>From</Text>
          <Text style={{ flex: 1, paddingLeft: 4 }}>To</Text>
        </View>
        <View style={s.boxRow}>
          <View style={[s.boxHalf, s.boxDivider]}>
            <Text style={s.line}>GSTIN: {from.gstin}</Text>
            <Text style={s.line}>{from.name}</Text>
            <Text style={s.line}>{from.state}</Text>
            <Text style={s.line}>::Dispatch::</Text>
            <Text>{from.address}</Text>
          </View>
          <View style={s.boxHalf}>
            <Text style={s.line}>GSTIN: {to.gstin}</Text>
            <Text style={s.line}>{to.name}</Text>
            <Text style={s.line}>{to.state}</Text>
            <Text style={s.line}>::Ship To::</Text>
            <Text>{to.address}</Text>
          </View>
        </View>

        <Text style={s.heading}>3.Goods Details</Text>
        <Table columns={GOODS_COLUMNS} rows={goods} />
        <Table columns={TOTAL_COLUMNS} rows={[{ key: 'totals', ...totals }]} />

        <Text style={s.heading}>4.Transportation Details</Text>
        <View style={s.gridRow}>
          <Pair label="Transporter ID & Name:" value={transport.transporter} />
          <Pair label="Transporter Doc. No & Date:" value={`${transport.docNo} & ${transport.docDate}`} />
        </View>

        <Text style={s.heading}>5.Vehicle Details</Text>
        <Table columns={VEHICLE_COLUMNS} rows={[{ key: 'vehicle', ...vehicle }]} />

        {model.cancelled ? (
          <Text style={s.watermark} fixed>
            CANCELLED
          </Text>
        ) : null}
      </Page>
    </Document>
  )
}
